/** The glyphs in a fixed order (the Arcade's retro font texture lays them out in this order) */
export const PIXEL_CHARS = Object.keys(PIXEL_FONT).join('');

/** Letters the font has: the rest of a text goes (accents lose theirs, lowercase is raised) */
export function pixelClean(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .split('')
    .filter((c) => PIXEL_FONT[c])
    .join('');
}

/** Width in pixels of a cleaned text, `k` pixels a font pixel */
export const pixelTextWidth = (s: string, k = 1) => (s.length ? s.length * 6 * k - k : 0);

/** Text in the pixel font, `k` pixels a font pixel, its top left at x, y (the text must be cleaned) */
export function drawPixelText(g: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, k = 1): void {
  g.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const glyph = PIXEL_FONT[s[i]];
    if (!glyph) continue;
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (glyph[r][c] === '#') g.fillRect(x + (i * 6 + c) * k, y + r * k, k, k);
  }
}
